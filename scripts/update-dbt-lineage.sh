#!/usr/bin/env bash
# Regenerate Formula/dbt-lineage.rb from the latest sipemu/dbt-lineage-viewer release.
set -euo pipefail
repo="sipemu/dbt-lineage-viewer"
tag="${1:-$(curl -fsSL "https://api.github.com/repos/$repo/releases/latest" | grep -m1 '"tag_name":' | sed -E 's/.*"(v[^"]+)".*/\1/')}"
version="${tag#v}"
base="https://github.com/$repo/releases/download/$tag"

sha() { curl -fsSL "$base/dbt-lineage-$tag-$1.tar.gz.sha256" | awk '{print $1}'; }
mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-gnu)
linux_intel=$(sha x86_64-unknown-linux-gnu)

cat > Formula/dbt-lineage.rb <<RUBY
# Generated by scripts/update-dbt-lineage.sh — do not edit by hand.
class DbtLineage < Formula
  desc "PR-time dbt lineage, impact analysis and rebuild plans without a warehouse"
  homepage "https://github.com/$repo"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/dbt-lineage-$tag-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/dbt-lineage-$tag-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base/dbt-lineage-$tag-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/dbt-lineage-$tag-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "dbt-lineage"
  end

  test do
    assert_match "dbt model lineage", shell_output("#{bin}/dbt-lineage --help")
  end
end
RUBY
echo "Formula/dbt-lineage.rb -> $version"
